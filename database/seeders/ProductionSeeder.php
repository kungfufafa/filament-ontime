    public function run(): void
    {
        $this->call(RoleSeeder::class);

        $companies = $this->seedCompanies();
        $jobLevels = $this->seedJobLevels();
        $divisionCache = [];
        $jobTitleCache = [];

        foreach ($this->employeeRecords() as $employee) {
            $company = $companies[$employee['company']];
            $division = $this->divisionFor($company, $employee, $divisionCache);
            $jobTitle = $this->jobTitleFor($division, $employee['job_title'], $jobTitleCache);

            Employee::updateOrCreate(
                ['nip' => $employee['nip']],
                [
                    'user_id' => null,
                    'company_id' => $company->id,
                    'division_id' => $division->id,
                    'job_level_id' => $jobLevels[$employee['job_level']]->id,
                    'job_title_id' => $jobTitle->id,
                    'full_name' => $employee['full_name'],
                    'email' => $employee['email'] ?: null,
                    'phone' => $employee['phone'] ?: null,
                    'join_date' => $employee['join_date'],
                    'status' => $employee['resign_date'] === '' ? 'active' : 'resigned',
                ],
            );
        }
    }

    /**
     * @return array<string, Company>
     */
    private function seedCompanies(): array
    {
        $companies = [];

        foreach (self::COMPANIES as $sourceName => $companyData) {
            $companies[$sourceName] = Company::updateOrCreate(
                ['code' => $companyData['code']],
                [
                    'name' => $companyData['name'],
                    'is_active' => true,
                ],
            );
        }

        return $companies;
    }

    /**
     * @return array<string, JobLevel>
     */
    private function seedJobLevels(): array
    {
        $jobLevels = [];

        foreach (self::JOB_LEVEL_ORDERS as $name => $order) {
            $jobLevels[$name] = JobLevel::updateOrCreate(
                ['name' => $name],
                ['level_order' => $order],
            );
        }

        return $jobLevels;
    }

    /**
     * @param  array<string, Division>  $divisionCache
     */
    private function divisionFor(Company $company, array $employee, array &$divisionCache): Division
    {
        $organization = $this->firstOrCreateDivision(
            $company,
            null,
            $employee['organization'],
            $divisionCache,
        );

        $subOrganization = $this->firstOrCreateDivision(
            $company,
            $organization,
            $employee['sub_organization'] ?: $employee['organization'],
            $divisionCache,
        );

        if ($employee['branch_detail'] === '') {
            return $subOrganization;
        }

        return $this->firstOrCreateDivision(
            $company,
            $subOrganization,
            $employee['branch_detail'],
            $divisionCache,
        );
    }

    /**
     * @param  array<string, Division>  $divisionCache
     */
    private function firstOrCreateDivision(
        Company $company,
        ?Division $parent,
        string $name,
        array &$divisionCache,
    ): Division {
        $cacheKey = implode('|', [$company->id, $parent?->id ?? 'root', $name]);

        return $divisionCache[$cacheKey] ??= Division::firstOrCreate(
            [
                'company_id' => $company->id,
                'parent_id' => $parent?->id,
                'name' => $name,
            ],
            ['is_active' => true],
        );
    }

    /**
     * @param  array<string, JobTitle>  $jobTitleCache
     */
    private function jobTitleFor(Division $division, string $name, array &$jobTitleCache): JobTitle
    {
        $cacheKey = implode('|', [$division->id, $name]);

        return $jobTitleCache[$cacheKey] ??= JobTitle::firstOrCreate([
            'division_id' => $division->id,
            'name' => $name,
        ]);
    }

    /**
     * @return list<array<string, string>>
     *
     * @throws JsonException
     */
    private function employeeRecords(): array
    {
        $compressedData = base64_decode(implode('', self::COMPRESSED_EMPLOYEE_DATA), true);
        $json = $compressedData === false ? false : zlib_decode($compressedData);

        if ($json === false) {
            throw new RuntimeException('Data karyawan production tidak dapat didekode.');
        }

        /** @var list<list<string>> $rows */
        $rows = json_decode($json, true, 512, JSON_THROW_ON_ERROR);

        return array_map(
            fn (array $row): array => array_combine(self::EMPLOYEE_FIELDS, $row),
            $rows,
        );
    }
